export function t(key) {
  const lang = Store.uiLang;
  const row = M[lang] || M.ko;
  if (row[key] != null) return row[key];
  return M.en[key] ?? M.ko[key] ?? key;
}

/** Keep definition and example translations in the selected UI language. */
export function wordMeaning(w) {
  if (!w) return '';
  if (typeof w.studyMeaning === 'string') return w.studyMeaning;
  const en = w.meaningEn ?? '';
  const ko = w.meaningKo ?? '';
  return (Store.uiLang === 'en' ? en : ko) || t('wordTranslationMissing');
}

export function sentenceMeaning(s) {
  if (!s) return '';
  if (typeof s.studyTranslation === 'string') return s.studyTranslation;
  const en = s.meaningEn ?? '';
  const ko = s.meaningKo ?? '';
  return (Store.uiLang === 'en' ? en : ko) || t('wordTranslationMissing');
}
